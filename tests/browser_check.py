    print('HISTORY:',p.locator('.receipts').inner_text())
    keyto('[data-action=open-share]'); keyto('#permission','Space')
    c.set_offline(True)
    p.wait_for_function("document.querySelector('.offline-banner')?.textContent.includes('browser offline')")
    check('Real browser offline revokes consent and disables send',not p.locator('#permission').is_checked() and p.locator('[data-send-revision]').is_disabled() and 'browser offline' in p.locator('.offline-banner').inner_text())
    snap('browser-offline')
    keyto('nav [data-tab=notes]'); keyto('nav [data-tab=companion]')
    check('Offline state survives navigation','browser offline' in p.locator('.offline-banner').inner_text())
    c.set_offline(False)
    p.wait_for_function("document.querySelector('.status-announcement')?.textContent.includes('no update queued or sent')")
    check('Recovery restores no permission and queues nothing',not p.locator('#permission').is_checked() and p.locator('[data-send-revision]').is_disabled() and 'no update queued or sent' in p.locator('.status-announcement').inner_text())
    keyto('.back')
    check('Real recovery retained note stage and single receipt',stage()=='Passport control' and '20 more minutes' in note() and '(1)' in p.locator('.receipts summary').inner_text())
    keyto('.current [data-stage]'); keyto('.current [data-stage]')
    check('Final stage offers completion',stage()=='Meet your chauffeur' and p.locator('[data-action=complete]').count()==1)
    keyto('[data-action=open-share]')
