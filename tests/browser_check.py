def note(): return p.locator('.check-in-card p').inner_text()
def audit(label):
    p.add_script_tag(path=f'{OUT}/axe.min.js')
    r=p.evaluate("async()=>await axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}})")
    audits.append({'view':label,'violations':r['violations'],'incomplete':r['incomplete']})
    check('axe '+label+' zero violations',len(r['violations'])==0)
    cs=p.evaluate("""()=>{const rgb=s=>(s.match(/[\\d.]+/g)||[]).map(Number);const lum=c=>c.slice(0,3).map(v=>v/255).map(v=>v<=.04045?v/12.92:((v+.055)/1.055)**2.4).reduce((a,v,i)=>a+v*[.2126,.7152,.0722][i],0);const rows=[];for(const e of document.querySelectorAll('*')){if(!e.getBoundingClientRect().width||![...e.childNodes].some(n=>n.nodeType===3&&n.textContent.trim()))continue;const s=getComputedStyle(e);let par=e,bg;while(par){bg=rgb(getComputedStyle(par).backgroundColor);if(bg.length===3||bg[3]===1)break;par=par.parentElement;}bg=bg||[255,255,255];let fg=rgb(s.color);let a=lum(fg),b=lum(bg);rows.push({text:e.textContent.trim().slice(0,80),color:s.color,bg:bg,ratio:(Math.max(a,b)+.05)/(Math.min(a,b)+.05)});}return rows}""")
    contrasts.append({'view':label,'text':cs})
    check('Text contrast >=4.5 '+label,all(x['ratio']>=4.5 for x in cs))
def layout(label):
    check('No horizontal overflow '+label,p.evaluate('document.documentElement.scrollWidth<=innerWidth'))
def footer(label):
    check('In-memory reset label '+label,'Reload to reset' in p.locator('.rider-footer').inner_text())
def reset():
    p.once('dialog',lambda d:d.accept())
    click('[data-reset]')
