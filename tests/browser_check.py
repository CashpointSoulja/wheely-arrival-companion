    check('Demo recovery retained note queues nothing','10 more minutes' in note() and p.locator('.receipts').count()==0)
    check('Recovered fixture label and description accurate',p.locator('#scenario option:checked').inner_text()=='No network · recovered' and p.locator('.scenario-description').inner_text()=='Demo connection restored. This fixture began offline. Progress kept; no updates queued or sent. Review permission again.')
