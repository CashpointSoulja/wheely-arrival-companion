    check('Cancel preserves saved note and stage','Waiting for bags' in note() and '20 more minutes' in note() and stage()=='Baggage reclaim')
    keyto('[data-action=open-check-in]'); keyto('input[value="Waiting for bags"]','ArrowLeft'); keyto('.back')
    check('Back discards draft only','Waiting for bags' in note() and '20 more minutes' in note())
    keyto('nav [data-tab=notes]')
    check('Notes view discloses reset and no storage','Application state is in memory only. Nothing is sent or stored. Reloading resets private progress and local update history.' in p.locator('.notes-page').inner_text())
    snap('product-notes'); audit('product notes')
    links=p.locator('.doc-list a')
    check('14 notebook links',links.count()==14)
    for i in range(links.count()):
        name=links.nth(i).inner_text()
        with c.expect_page() as opened: links.nth(i).click()
        doc=opened.value; doc.wait_for_load_state()
        body=doc.locator('body').inner_text()
        check('Notebook '+name,len(body)>100 and body.lstrip().startswith('#') and doc.url.endswith('.md'))
        doc.close()
    keyto('nav [data-tab=companion]')
    check('Notes navigation preserves progress and note',stage()=='Baggage reclaim' and 'Waiting for bags' in note())
    p.once('dialog',lambda d:d.dismiss()); keyto('[data-reset]')
    check('Canceled reset preserves note and progress',stage()=='Baggage reclaim' and '20 more minutes' in note())
    keyto('[data-action=open-share]'); footer('preview'); audit('preview')
    text=p.locator('.message-preview p').inner_text()
    check('Exact Morgan preview excludes private reason and estimate',text=='The passenger reports: Baggage reclaim. They are taking a little longer and will update you when ready.' and 'MORGAN' in p.locator('.message-preview').inner_text())
    check('Consent off by default and send disabled',not p.locator('#permission').is_checked() and p.locator('[data-send-revision]').is_disabled())
    p.locator('.message-preview').scroll_into_view_if_needed(); snap('consent-preview',False)
    keyto('[data-action=withdraw]')
    check('Refusal returns to timeline without nag',stage()=='Baggage reclaim' and p.locator('#permission').count()==0 and p.locator('.receipts').count()==0)
    keyto('[data-action=open-share]'); keyto('#permission','Space'); keyto('[data-send-revision]')
    check('One local receipt, explicit nothing sent',p.locator('.receipts summary').inner_text()=='Simulated update history (1)' and 'Nothing was sent' in p.locator('.status-announcement').inner_text())
    keyto('.receipts summary'); snap('local-receipt')
