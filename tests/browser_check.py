    b=pw.chromium.launch(**({'executable_path': CHROME} if CHROME else {}),headless=True,args=['--no-sandbox'])
    c=b.new_context(viewport={'width':390,'height':844},device_scale_factor=2)
    p=c.new_page(); p.on('request',lambda r:requests.append({'url':r.url,'method':r.method})); p.on('pageerror',lambda e:errors.append(str(e)))
    p.goto(BASE)
    check('Initial Landed; no premature completion',stage()=='Landed' and p.locator('[data-action=complete]').count()==0)
