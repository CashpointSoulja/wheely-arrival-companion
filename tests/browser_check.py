results=[]; audits=[]; requests=[]; errors=[]; contrasts=[]
def check(name,value):
    results.append({'assertion':name,'passed':bool(value)})
    print(('PASS ' if value else 'FAIL ')+name,flush=True)
def snap(name,full=True):
    p.screenshot(path=f'{OUT}/{name}.png',full_page=full)
def click(sel): p.locator(sel).click()
def keyto(sel,key='Enter'):
    for _ in range(100):
        if p.locator(sel).evaluate('(e)=>e===document.activeElement'):
            p.keyboard.press(key); return
        p.keyboard.press('Tab')
    raise Exception('Cannot keyboard reach '+sel)
